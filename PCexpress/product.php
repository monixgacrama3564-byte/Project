    const sub = cartItems.reduce((s, i) => s + (i.priceRaw * i.qty), 0);

    container.innerHTML = cartItems.map(item => `
        <div class="summary-item">
            <div class="summary-item-img-wrap">
                <img src="${item.image}" class="summary-item-img" alt="${item.name}"
                     onerror="this.src='https://via.placeholder.com/64x64?text=Product'">
                <div class="summary-item-qty-badge">${item.qty}</div>
            </div>
            <div class="summary-item-info">
                <div class="summary-item-name">${item.name}</div>
                ${item.oldPrice ? `<div class="summary-item-sub">Was ${item.oldPrice}</div>` : ''}
            </div>
            <div class="summary-item-price">${fmt(item.priceRaw * item.qty)}</div>
        </div>
    `).join('');

    document.getElementById('summarySubtotal').textContent = fmt(sub);
    document.getElementById('summaryTotal').textContent    = fmt(sub);
}

/* ── PAYMENT SELECTION ── */
function selectPayment(type) {
    ['ipay', 'bank'].forEach(id => {
        const el  = document.getElementById('pay-' + id);
        el.classList.toggle('selected', id === type);
        const dot = el.querySelector('.payment-radio-inner');
        if (dot) dot.style.display = (id === type) ? 'block' : 'none';
    });
    const det = document.getElementById('payDetailIpay');
    if (det) det.style.display = (type === 'ipay') ? 'block' : 'none';
}

/* ── BILLING SELECTION ── */
function selectBilling(type) {
    const same = document.getElementById('bill-same');
    const diff = document.getElementById('bill-different');
    const dRad = document.getElementById('billDiffRadio');
    const dDot = document.getElementById('billDiffDot');
    if (type === 'same') {
        same.classList.add('selected');   diff.classList.remove('selected');
        dRad.style.borderColor = '#bbb';  dDot.style.display = 'none';
    } else {
        same.classList.remove('selected'); diff.classList.add('selected');
        dRad.style.borderColor = '#003da5'; dDot.style.display = 'block';
    }
}

