window.addEventListener('DOMContentLoaded', function() {
    const params = new URLSearchParams(window.location.search);
    if (params.get('checkout') === '1') {
        // Wait for cart to load (cart.js fires loadCart on DOMContentLoaded too)
        setTimeout(function() {
            if (cartItems.length > 0) {
                // Auto-check terms and open checkout
                const agreed = document.getElementById('agreeTerms');
                if (agreed) agreed.checked = true;
                buildCheckoutSummary();
                document.getElementById('checkoutPage').classList.add('open');
                document.body.style.overflow = 'hidden';
            }
        }, 100);
    }
});
