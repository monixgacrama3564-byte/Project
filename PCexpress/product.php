function saveCart() {
    // 1. Always save to localStorage (guest + logged-in fallback)
    try { 
        localStorage.setItem('pcx_cart', JSON.stringify(
            cartItems.map(item => ({
                ...item,
                // Normalize price to a clean number before saving
                priceRaw: typeof item.priceRaw === 'number' ? item.priceRaw 
                          : parseFloat(String(item.priceRaw || item.price || 0).replace(/[^0-9.]/g, '')) || 0,
                price: typeof item.priceRaw === 'number' ? item.priceRaw 
                       : parseFloat(String(item.priceRaw || item.price || 0).replace(/[^0-9.]/g, '')) || 0,
            }))
        )); 
    } catch(e) {}
    
    // 2. Sync to Firestore if logged in
    syncCartToFirestore();
}

async function syncCartToFirestore() {
    if (typeof window._firebaseAuth === 'undefined') return;
    const user = window._firebaseAuth?.currentUser;
    if (!user) return;

    try {
        const { db } = await import('./firebase-config.js');
        const { collection, doc, setDoc, getDocs, deleteDoc, writeBatch } 
            = await import('https://www.gstatic.com/firebasejs/10.12.0/firebase-firestore.js');
        
        const cartCol = collection(db, 'carts', user.uid, 'items');
        
        // Delete existing items
        const existing = await getDocs(cartCol);
        const batch = writeBatch(db);
        existing.docs.forEach(d => batch.delete(d.ref));
        
        // Write current items
        cartItems.forEach(item => {
            const cleanPrice = typeof item.priceRaw === 'number' ? item.priceRaw
                : parseFloat(String(item.priceRaw || item.price || 0).replace(/[^0-9.]/g, '')) || 0;
            const itemRef = doc(cartCol, item.id);
            batch.set(itemRef, {
                productName:  item.name  || 'Product',
                productPrice: cleanPrice,          // ← always a NUMBER
                productImage: item.image || '',
                variant:      item.variant || '',
                qty:          item.qty || 1,
            });
        });
        
        await batch.commit();
    } catch(err) {
        console.warn('syncCartToFirestore:', err);
    }
}
