/* ── TOAST ── */
function showToast(name) {
    const short = name.length > 45 ? name.substring(0, 45) + '…' : name;
    document.getElementById('cartToastMsg').textContent = short + ' added to cart!';
    const t = document.getElementById('cartToast');
    t.classList.add('show');
    setTimeout(() => t.classList.remove('show'), 3000);
}

/* ── CART SUB-PANELS ── */
let orderNote = '';
let couponCode = '';

const shippingRates = {
    'metro manila': { label: 'Standard Metro Manila',   amount: 150 },
    'cebu':         { label: 'LBC Visayas Rate',         amount: 3106.38 },
    'davao del sur':{ label: 'LBC Mindanao Rate',        amount: 350 },
    'default':      { label: 'Standard Nationwide Rate', amount: 250 },
};

function closeCartPanel() {
    document.querySelectorAll('.cart-subpanel').forEach(p => p.style.display = 'none');
}
function openNotePanel() {
    closeCartPanel();
    document.getElementById('cartNotePanel').style.display = 'block';
    const ta = document.getElementById('cartNoteInput');
    if (ta) ta.value = orderNote;
}
function saveNote() {
    const ta = document.getElementById('cartNoteInput');
    orderNote = ta ? ta.value.trim() : '';
    try { localStorage.setItem('pcx_note', orderNote); } catch(e) {}
    closeCartPanel();
}
function openShippingPanel() {
    closeCartPanel();
    document.getElementById('cartShippingPanel').style.display = 'block';
    document.getElementById('shippingResult').innerHTML = '';
}
function estimateShipping() {
    const province = (document.getElementById('shippingProvince').value || '').trim().toLowerCase();
    const zip      = (document.getElementById('shippingZip').value || '').trim();
    if (!province || !zip) {
        document.getElementById('shippingResult').innerHTML =
            '<p style="color:#c00;font-size:13px;">Please select a Province and enter a Zip code.</p>';
        return;
    }
    const rate = shippingRates[province] || shippingRates['default'];
    document.getElementById('shippingResult').innerHTML = `
        <p style="color:#cc0000;font-size:13px;margin-top:10px;">
            We found one shipping rate available for ${zip}, ${province.replace(/\b\w/g,c=>c.toUpperCase())}, Philippines.
        </p>
        <ul style="font-size:13px;margin:6px 0 0 16px;color:#333;">
            <li>${rate.label} at ₱${rate.amount.toLocaleString('en-PH',{minimumFractionDigits:2,maximumFractionDigits:2})}</li>
        </ul>`;
}
function openCouponPanel() {
    closeCartPanel();
    document.getElementById('cartCouponPanel').style.display = 'block';
    const inp = document.getElementById('cartCouponInput');
    if (inp) inp.value = couponCode;
}
function saveCoupon() {
    const inp = document.getElementById('cartCouponInput');
    couponCode = inp ? inp.value.trim() : '';
    try { localStorage.setItem('pcx_coupon', couponCode); } catch(e) {}
    closeCartPanel();
    if (couponCode) showToast('Coupon "' + couponCode + '" saved!');
}

